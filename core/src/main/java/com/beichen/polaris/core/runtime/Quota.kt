package com.beichen.polaris.core.runtime

/**
 * 一个回合的配额。
 *
 * ## 为什么三项默认都是 0
 *
 * 0 表示「这一项我没说」，由 [QuotaResolver] 在接线时落成具体上限。
 * 为什么不把默认写成 20 / 60 这种具体数字：数据类里写死默认值，等于让
 * 「没表态」和「表态成这个数」变成同一个值——三个入口（主界面 60 步、
 * 桌宠 6 步、子代理 8 步）一旦有人忘了传，谁也看不出是默认还是覆盖。
 * 0 是一个不可能被误当成「有效配额」的值（loop 里 `repeat(0)` 一步都不跑），
 * 所以任何绕过 [QuotaResolver] 直接用它的代码都会当场暴露，而不是静默降额。
 *
 * ## `maxTokens` 为什么也在但暂未消费
 *
 * 落地时只接通了 steps / deadline 两项：loop 里没有按 token 截断的位置，
 * 硬造一个「token 计数」只会得到一个永远不触发的上限（比没有更糟）。
 * 字段留着是为了让「要加 token 预算」这件事有地方落，但**不要假装它生效**。
 */
data class Quota(
    /** 最大步数。0 = 不设，落到接线方的兜底值。 */
    val maxSteps: Int = 0,
    /** token 上限。0 = 不设。当前无消费点，见类注释。 */
    val maxTokens: Int = 0,
    /** 单回合墙钟预算（毫秒）。0 = 不设，落到接线方的兜底值。 */
    val deadlineMs: Long = 0L,
)
